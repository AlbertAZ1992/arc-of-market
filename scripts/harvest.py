def cboe_daily_close(symbol: str) -> pd.Series:
    """Load a Cboe index's published daily close history."""
    response = requests.get(
        CBOE_HISTORY_URL.format(symbol=symbol),
        headers=UA,
        timeout=30,
    )
    response.raise_for_status()
    table = pd.read_csv(StringIO(response.text))
    table.columns = [str(column).strip().upper() for column in table.columns]
    if "DATE" not in table.columns:
        raise ValueError(f"Cboe {symbol} response has no DATE column")
    value_column = "CLOSE" if "CLOSE" in table.columns else str(table.columns[-1])
    observations = table.loc[:, ["DATE", value_column]].copy()
    observations["DATE"] = pd.to_datetime(observations["DATE"], errors="coerce")
    observations[value_column] = pd.to_numeric(observations[value_column], errors="coerce")
    observations = observations.dropna().drop_duplicates("DATE", keep="last")
    if observations.empty:
        raise ValueError(f"Cboe {symbol} response contains no numeric observations")
    return observations.set_index("DATE")[value_column].sort_index()


