FRED_OBSERVATIONS_URL = "https://api.stlouisfed.org/fred/series/observations"


def fred_series(series_id: str, start: str = "1900-01-01") -> pd.Series:
    """Fetch one latest-vintage FRED series through the documented JSON endpoint."""
    api_key = os.environ.get("FRED_API_KEY", "").strip()
    if not api_key:
        raise RuntimeError("FRED_API_KEY is required for FRED API requests")
    parameters = {
        "api_key": api_key,
        "file_type": "json",
        "observation_start": start,
        "series_id": series_id,
        "sort_order": "asc",
    }
    last_error: Exception | None = None
    for attempt in range(3):
        try:
            response = requests.get(
                FRED_OBSERVATIONS_URL,
                params=parameters,
                headers=UA,
                timeout=60,
            )
            response.raise_for_status()
            return _fred_observations(response.json(), series_id)
        except (requests.RequestException, KeyError, TypeError, ValueError) as error:
            last_error = error
            if attempt < 2:
                time.sleep(2**attempt)
    raise RuntimeError(f"FRED {series_id} request failed") from last_error


def _fred_observations(payload: dict[str, Any], series_id: str) -> pd.Series:
    rows = payload.get("observations")
    if not isinstance(rows, list):
        raise ValueError(f"FRED {series_id} response has no observations array")
    table = pd.DataFrame.from_records(rows)
    if not {"date", "value"}.issubset(table.columns):
        raise ValueError(f"FRED {series_id} observations have an unexpected schema")
    table["date"] = pd.to_datetime(table["date"], errors="coerce")
    table["value"] = pd.to_numeric(table["value"].replace({".": None}), errors="coerce")
    table = table.dropna(subset=["date", "value"]).drop_duplicates("date", keep="last")
    if table.empty:
        raise ValueError(f"FRED {series_id} contains no numeric observations")
    return table.set_index("date")["value"].sort_index()


def _weekly(s: pd.Series, nd: int = 2) -> dict:
    w = weekly_last(s)
    return {"dates": dates(w.index), "values": rnd(w, nd)}


def percent_change_payload(
    series: pd.Series,
    precision: int = 2,
    lag: int = 12,
) -> dict:
    """Return percentage changes while treating a zero prior value as missing."""
    prior_values = series.shift(lag)
    valid_prior_values = prior_values.where(prior_values.ne(0))
    percentage_changes = series.sub(prior_values).div(valid_prior_values).mul(100).dropna()
    return {
        "dates": dates(percentage_changes.index),
        "values": rnd(percentage_changes, precision),
    }


def _period(s: pd.Series, nd: int = 1) -> dict:
    """月/季频序列保留 FRED observation_date。"""
    values = s.dropna()
    return {"dates": dates(values.index), "values": rnd(values, nd)}


