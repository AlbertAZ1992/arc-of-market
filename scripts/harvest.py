def merge_valuation_observation(
    existing: dict[str, Any],
    as_of: str,
    trailing_pe: float,
) -> dict[str, list[Any]]:
    """按日期合并估值快照；同日重跑会替换，不会制造重复观察。"""
    existing_dates = existing.get("dates", [])
    existing_values = existing.get("trailing_pe", [])
    if not isinstance(existing_dates, list) or not isinstance(existing_values, list):
        raise ValueError("existing valuation proxy must contain arrays")
    if len(existing_dates) != len(existing_values):
        raise ValueError("valuation proxy dates and values must have equal length")
    observations: dict[str, float] = {}
    for date, value in zip(existing_dates, existing_values, strict=True):
        if value is None:
            continue
        if not isinstance(value, int | float):
            raise ValueError("valuation proxy observations must be numeric")
        observations[str(date)] = float(value)
    observations[as_of] = round(trailing_pe, 4)
    ordered_dates = sorted(observations)
    return {
        "dates": ordered_dates,
        "trailing_pe": [observations[date] for date in ordered_dates],
    }


