def build_index_panels(prefix: str, close: pd.Series, vol_index=None, vol_name="") -> None:
    """生成长期、年度、回撤、滚动、波动率和季节性基础面板。"""
    print(f"== panels {prefix}")
    values = close.dropna().sort_index()
    month_end = monthly_last(values)
    drawdowns, episodes = drawdown_history(values)
    weekly_drawdowns = weekly_min(drawdowns).mul(100)
    payloads = {
        "century": {
            "dates": dates(values.index),
            "close": rnd(values, 2),
            "return_type": "price",
        },
        "annual": annual_performance(values),
        "drawdowns": {
            "dates": dates(weekly_drawdowns.index),
            "dd": rnd(weekly_drawdowns, 2),
            "episodes": sorted(episodes, key=lambda row: row["depth"])[:25],
            "return_type": "price",
        },
        "intrayear": intrayear_performance(values),
        "rolling5y": rolling_five_year_performance(month_end),
        "volatility": volatility_history(values, vol_index, vol_name),
        "seasonality": monthly_seasonality(month_end),
    }
    for suffix, payload in payloads.items():
        pin(f"{prefix}_{suffix}.json", payload)


