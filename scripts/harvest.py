def weekly_last(s: pd.Series) -> pd.Series:
    """按周抽取最后一个真实 observation_date。"""
    return s.dropna().groupby(pd.Grouper(freq="W")).tail(1)


def weekly_min(s: pd.Series) -> pd.Series:
    """按周抽取最小值及其真实 observation_date。"""
    values = s.dropna()
    weeks = pd.DatetimeIndex(values.index).to_period("W-SUN")
    indices = values.groupby(weeks).idxmin()
    return values.loc[indices.tolist()]


def monthly_last(s: pd.Series, include_partial: bool = False) -> pd.Series:
    """按月抽取最后一个真实 observation_date，默认排除未结束月份。"""
    values = s.dropna()
    months = pd.DatetimeIndex(values.index).to_period("M")
    result = values.groupby(months).tail(1)
    if result.empty or include_partial:
        return result
    latest_timestamp = cast(pd.Timestamp, pd.Timestamp(cast(Any, result.index[-1])))
    latest_period_end = latest_timestamp.to_period("M").end_time.date()
    if datetime.now(UTC).date() <= latest_period_end:
        return result.iloc[:-1]
    return result


# Regime Rotation 旗舰指数（占位待用户最终确认旗舰）
# 移植自 strategy-ai/qqq/strategy.py 的 determine_state 计算逻辑（自写，只移植算法不抄源码）。
# 六状态：NORMAL / BEAR_CASH / ZONE_BATTLE_DEFEND / ZONE_BATTLE_ATTACK /
# ZONE_DESPAIR_TQQQ / TOP_ESCAPE。
# 输出每日权重、回撤、权益曲线与 20/40/60/120/250 交易日信号对账。

REGIME_WEIGHTS = {
    "NORMAL": {"qqq": 0.45, "tqqq": 0.45},
    "BEAR_CASH": {"qqq": 0.0, "tqqq": 0.0},
    "ZONE_BATTLE_DEFEND": {"qqq": 0.90, "tqqq": 0.0},
    "ZONE_BATTLE_ATTACK": {"qqq": 0.0, "tqqq": 0.99},
    "ZONE_DESPAIR_TQQQ": {"qqq": 0.0, "tqqq": 0.99},
    "TOP_ESCAPE": {"qqq": 0.90, "tqqq": 0.0},
}


def determine_state(close, ma200, ma20, drawdown, is_top_signal) -> str:
    """按 strategy-ai 默认阈值判定六种市场状态。"""
    if is_top_signal:
        return "TOP_ESCAPE"
    if ma200 is not None and close < ma200:
        if drawdown <= -0.30:
            return "ZONE_DESPAIR_TQQQ"
        elif drawdown <= -0.10:
            if ma20 is not None and close > ma20:
                return "ZONE_BATTLE_ATTACK"
            return "ZONE_BATTLE_DEFEND"
        return "BEAR_CASH"
    if drawdown < -0.10:
        return "ZONE_BATTLE_ATTACK"
    return "NORMAL"


def detect_top_signal(
    close: float,
    open_price: float,
    volume: float,
    volume_average: float,
    ath: float,
) -> bool:
    """接近历史高点时出现两倍 60 日均量的阴线。"""
    return close >= 0.95 * ath and volume > 2.0 * volume_average and close < open_price


def build_regime_rotation() -> None:
    print("== Regime Rotation（旗舰占位）")
    qqq_history = fetch_history("QQQ")[["Open", "High", "Close", "Volume"]].dropna()
    tqqq = fetch_history("TQQQ")["Close"].dropna()
    df = qqq_history.rename(
        columns={"Open": "open", "High": "high", "Close": "qqq", "Volume": "volume"}
    ).join(tqqq.rename("tqqq"), how="inner")
    close = df["qqq"]
    ma200 = close.rolling(200).mean()
    ma20 = close.rolling(20).mean()
    volume_ma60 = df["volume"].rolling(60).mean()
    ath = df["high"].cummax()
    drawdown = close / ath - 1.0

    rows = []
    for i in range(len(close)):
        if pd.isna(ma200.iloc[i]) or pd.isna(volume_ma60.iloc[i]):
            continue
        c = float(close.iloc[i])
        m2 = float(ma20.iloc[i]) if not pd.isna(ma20.iloc[i]) else None
        dd = float(drawdown.iloc[i])
        is_top = detect_top_signal(
            close=c,
            open_price=float(df["open"].iloc[i]),
            volume=float(df["volume"].iloc[i]),
            volume_average=float(volume_ma60.iloc[i]),
            ath=float(ath.iloc[i]),
        )
        state = determine_state(c, float(ma200.iloc[i]), m2, dd, is_top)
        rows.append(
            {
                "date": close.index[i].strftime("%Y-%m-%d"),
                "state": state,
                "qqq_weight": REGIME_WEIGHTS[state]["qqq"],
                "tqqq_weight": REGIME_WEIGHTS[state]["tqqq"],
                "qqq_drawdown": round(dd, 4),
            }
        )

    # 权益曲线（简化版：每日按状态权重加权 QQQ/TQQQ 收益；T+1 暂不纳入，方法论页注明差异）
    ret = df.pct_change()
    port = []
    eq = 1.0
    eq_peak = 1.0
    qqq_equity = 1.0
    for i in range(1, len(rows)):
        idx = close.index.get_indexer([pd.Timestamp(rows[i]["date"])])[0]
        w = REGIME_WEIGHTS[str(rows[i - 1]["state"])]
        daily = w["qqq"] * float(ret["qqq"].iloc[idx]) + w["tqqq"] * float(ret["tqqq"].iloc[idx])
        eq *= 1 + daily
        eq_peak = max(eq_peak, eq)
        qqq_equity *= 1 + float(ret["qqq"].iloc[idx])
        port.append(
            {
                "date": rows[i]["date"],
                "equity": round(eq, 4),
                "qqq_equity": round(qqq_equity, 4),
                "strategy_drawdown": round(eq / eq_peak - 1, 4),
            }
        )

    pin(
        "regime_rotation.json",
        {
            "dates": [r["date"] for r in rows],
            "states": [r["state"] for r in rows],
            "qqq_drawdown": [r["qqq_drawdown"] for r in rows],
            "equity_curve": port,
            "states_meta": REGIME_WEIGHTS,
            "source": "QQQ/TQQQ via Yahoo Finance；状态机参考 strategy-ai 口径",
            "return_type": "Yahoo auto-adjusted ETF returns",
            "caveat": "研究指标：未计交易成本、税费和滑点，不构成可直接交易的回测结果",
        },
    )


