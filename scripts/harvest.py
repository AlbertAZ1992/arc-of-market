def calculate_forward_pe(index_level: float, ntm_eps: float) -> float:
    """Forward PE = 当前指数点位 / 分析师未来十二个月一致预期 EPS。"""
    if index_level <= 0:
        raise ValueError("index level must be positive")
    if ntm_eps <= 0:
        raise ValueError("NTM EPS must be positive")
    return index_level / ntm_eps


def _forward_eps_input() -> dict[str, str | float] | None:
    """读取经授权的一致预期 EPS 快照；缺字段时视为不可用，绝不伪造。"""
    raw_eps = os.environ.get("SP500_FORWARD_EPS_NTM", "").strip()
    if not raw_eps:
        return None
    as_of = os.environ.get("SP500_FORWARD_EPS_AS_OF", "").strip()
    source = os.environ.get("SP500_FORWARD_EPS_SOURCE", "").strip()
    license_scope = os.environ.get("SP500_FORWARD_EPS_LICENSE_SCOPE", "internal").strip()
    if not as_of or not source:
        raise ValueError(
            "SP500_FORWARD_EPS_AS_OF and SP500_FORWARD_EPS_SOURCE are required "
            "when SP500_FORWARD_EPS_NTM is set"
        )
    as_of_date = datetime.fromisoformat(as_of).date()
    age_days = (datetime.now(UTC).date() - as_of_date).days
    if age_days < 0:
        raise ValueError("SP500_FORWARD_EPS_AS_OF cannot be in the future")
    if age_days > 45:
        raise ValueError(f"forward EPS consensus is stale by {age_days} days")
    if license_scope not in {"internal", "public"}:
        raise ValueError("SP500_FORWARD_EPS_LICENSE_SCOPE must be internal or public")
    eps = float(raw_eps)
    if eps <= 0:
        raise ValueError("SP500_FORWARD_EPS_NTM must be positive")
    return {
        "ntm_eps": eps,
        "as_of": as_of,
        "source": source,
        "license_scope": license_scope,
    }


