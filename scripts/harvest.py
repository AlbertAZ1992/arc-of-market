def _optional_text(value: Any) -> str | None:
    if pd.isna(value):
        return None
    text = str(value).strip()
    return text or None


def _parse_sp500_changes_table(table: pd.DataFrame) -> list[dict[str, Any]]:
    """把 Wikipedia 多层表头转换为稳定的成分变更事件。"""
    required = {
        ("Effective Date", "Effective Date"),
        ("Added", "Ticker"),
        ("Added", "Security"),
        ("Removed", "Ticker"),
        ("Removed", "Security"),
        ("Reason", "Reason"),
    }
    if not required.issubset(set(table.columns)):
        raise ValueError("Wikipedia constituent-change table schema changed")

    changes = []
    seen = set()
    for _, row in table.iterrows():
        effective = pd.to_datetime(row[("Effective Date", "Effective Date")], errors="coerce")
        if pd.isna(effective):
            continue
        added_ticker = _optional_text(row[("Added", "Ticker")])
        removed_ticker = _optional_text(row[("Removed", "Ticker")])
        key = (effective.date().isoformat(), added_ticker, removed_ticker)
        if key in seen:
            raise ValueError(f"duplicate constituent change: {key}")
        seen.add(key)
        reason = _optional_text(row[("Reason", "Reason")])
        changes.append(
            {
                "effective_date": effective.date().isoformat(),
                "addition": {
                    "ticker": added_ticker,
                    "name": _optional_text(row[("Added", "Security")]),
                },
                "removal": {
                    "ticker": removed_ticker,
                    "name": _optional_text(row[("Removed", "Security")]),
                },
                "reason": re.sub(r"\[\d+(?:,\s*\d+)*\]", "", reason).strip() if reason else None,
            }
        )
    return sorted(changes, key=lambda item: item["effective_date"], reverse=True)


