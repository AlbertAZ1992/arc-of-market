def run_section(
    label: str,
    operation: Callable[..., Any],
    *args: Any,
    blocking: bool = True,
    **kwargs: Any,
) -> bool:
    """Run one pipeline step and record a structured failure when it cannot finish."""
    result = CallResult.invoke(operation, *args, **kwargs)
    if result.succeeded:
        return True
    error = result.error or RuntimeError("pipeline step failed without an error")
    failure = {
        "section": label,
        "error": f"{type(error).__name__}: {str(error)[:200]}",
        "blocking": blocking,
    }
    _FAILURES.append(failure)
    print(f"  ⚠️ {label} 失败（保留上一版文件）: {failure['error']}")
    return False


def normalized_timestamp(value: Any) -> pd.Timestamp:
    """把 pandas 可识别日期转为无时区的日粒度 Timestamp。"""
    timestamp = cast(pd.Timestamp, pd.Timestamp(value))
    naive = timestamp.tz_localize(None)
    return naive.normalize()


def fetch_history(
    ticker: str,
    retries: int = 4,
    expected_date: pd.Timestamp | None = None,
) -> pd.DataFrame:
    """yfinance 历史价。BRK.B 用连字符、欧股 MC.PA 保留点：原样优先、连字符兜底。
    让 yfinance 管理 curl_cffi 会话、cookie 与 crumb；失败时指数退避。"""
    candidates = [ticker] + ([ticker.replace(".", "-")] if "." in ticker else [])
    for i in range(retries):
        for sym in candidates:
            try:
                # 不传 requests.Session：它没有浏览器 TLS/HTTP2 指纹，会被 Yahoo 直接限流。
                t = yf.Ticker(sym)
                df = t.history(period="max", auto_adjust=True)
                repaired_date = None
                incomplete_latest = (
                    "Close" in df.columns and not df.empty and pd.isna(df["Close"].iloc[-1])
                )
                latest_date = normalized_timestamp(df.index[-1]) if not df.empty else None
                lagging_latest = (
                    expected_date is not None
                    and latest_date is not None
                    and latest_date < normalized_timestamp(expected_date)
                )
                was_incomplete = incomplete_latest
                was_lagging = lagging_latest
                if incomplete_latest or lagging_latest:
                    try:
                        repair = t.history(
                            period="10d",
                            auto_adjust=True,
                            repair=True,
                            keepna=True,
                        )
                        repair = repair.drop(columns=["Repaired?"], errors="ignore")
                        if not repair.empty:
                            repair_start = repair.index.min()
                            df = pd.concat([df.loc[df.index < repair_start], repair]).sort_index()
                            repaired_latest = normalized_timestamp(df.index[-1])
                            caught_up = expected_date is None or normalized_timestamp(
                                repaired_latest
                            ) >= normalized_timestamp(expected_date)
                            if (
                                "Close" in df.columns
                                and not pd.isna(df["Close"].iloc[-1])
                                and (was_incomplete or (was_lagging and caught_up))
                            ):
                                repaired_date = repaired_latest.strftime("%Y-%m-%d")
                    except Exception as repair_error:
                        print(f"  {sym} repair failed: {str(repair_error)[:80]}")
                    incomplete_latest = (
                        "Close" in df.columns and not df.empty and pd.isna(df["Close"].iloc[-1])
                    )
                    latest_date = normalized_timestamp(df.index[-1]) if not df.empty else None
                    lagging_latest = (
                        expected_date is not None
                        and latest_date is not None
                        and latest_date < normalized_timestamp(expected_date)
                    )
                incomplete_date = (
                    pd.Timestamp(cast(Any, df.index[-1])).strftime("%Y-%m-%d")
                    if incomplete_latest
                    else None
                )
                if "Close" in df.columns:
                    df = df.dropna(subset=["Close"])
                if len(df) > 100:
                    df.index = df.index.tz_localize(None)
                    if incomplete_date is not None:
                        _FAILURES.append(
                            {
                                "section": f"source yahoo:{sym}",
                                "error": (
                                    f"latest row {incomplete_date} has no close; "
                                    f"using {df.index[-1].strftime('%Y-%m-%d')}"
                                ),
                                "blocking": False,
                            }
                        )
                    if lagging_latest and expected_date is not None:
                        _FAILURES.append(
                            {
                                "section": f"source yahoo:{sym}",
                                "error": (
                                    f"latest close {df.index[-1].strftime('%Y-%m-%d')} "
                                    f"lags expected {expected_date.strftime('%Y-%m-%d')}"
                                ),
                                "blocking": False,
                            }
                        )
                    trace = f"Yahoo({len(df)} rows,{df.index[-1].strftime('%Y-%m-%d')}"
                    if repaired_date is not None:
                        trace += f",repaired={repaired_date}"
                    _SOURCE_TRACE[f"yahoo:{sym}"] = f"{trace})"
                    return df
            except Exception as e:
                print(f"  {sym} attempt {i + 1} failed: {str(e)[:80]}")
        # 指数退避:2,4,8,16 秒,给限流恢复时间
        time.sleep(2 ** (i + 1))
    raise RuntimeError(f"failed to fetch {ticker}")


def dates(idx) -> list:
    return [d.strftime("%Y-%m-%d") for d in idx]


def rnd(s, n=2) -> list:
    return [None if pd.isna(v) else round(float(v), n) for v in s]


