def load_profile_runs() -> dict[str, dict]:
    path = DATA / "meta.json"
    if not path.exists():
        return {}
    try:
        existing = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    profile_runs = existing.get("profile_runs")
    if isinstance(profile_runs, dict):
        return profile_runs
    profile = existing.get("profile")
    if not isinstance(profile, str):
        return {}
    return {
        profile: {
            "updated": existing.get("updated"),
            "source_trace": existing.get("source_trace", {}),
            "failures": existing.get("failures", []),
        }
    }


