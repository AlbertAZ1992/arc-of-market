def _parse_ofr_fsi(csv_text: str, today: pd.Timestamp | None = None) -> dict[str, Any]:
    """校验 OFR FSI 下载文件，并保留总指数、类别和地区贡献。"""
    frame = pd.read_csv(StringIO(csv_text))
    required = ["Date", *OFR_FSI_FIELDS.values()]
    missing = [column for column in required if column not in frame.columns]
    if missing:
        raise ValueError(f"OFR FSI missing columns: {', '.join(missing)}")

    frame = frame[required].copy()
    frame["Date"] = pd.to_datetime(frame["Date"], errors="coerce")
    for column in OFR_FSI_FIELDS.values():
        frame[column] = pd.to_numeric(frame[column], errors="coerce")
    if frame.isna().any().any():
        bad_rows = int(frame.isna().any(axis=1).sum())
        raise ValueError(f"OFR FSI contains {bad_rows} incomplete rows")
    if frame["Date"].duplicated().any():
        raise ValueError("OFR FSI contains duplicate dates")

    frame = frame.sort_values("Date")
    if len(frame) < 5_000:
        raise ValueError(f"OFR FSI coverage unexpectedly low: {len(frame)} rows")

    current_day = today if today is not None else pd.Timestamp.now(tz="UTC")
    checked_today = normalized_timestamp(current_day)
    latest = normalized_timestamp(frame["Date"].iloc[-1])
    if latest > checked_today:
        raise ValueError(f"OFR FSI latest date is in the future: {latest.date()}")
    age_days = int((checked_today - latest).days)
    if age_days > 10:
        raise ValueError(f"OFR FSI is stale by {age_days} calendar days")

    date_values = dates(pd.DatetimeIndex(frame["Date"]))
    series = {
        key: {
            "dates": date_values,
            "values": rnd(frame[column], 3),
            "unit": "index contribution",
        }
        for key, column in OFR_FSI_FIELDS.items()
    }
    latest_values = {}
    for key, column in OFR_FSI_FIELDS.items():
        latest_values[key] = round(float(frame[column].iloc[-1]), 3)
    return {
        "meta": {
            "name": "OFR Financial Stress Index",
            "coverage_start": date_values[0],
            "coverage_end": date_values[-1],
            "row_count": len(frame),
            "frequency": "daily",
            "availability_lag": "two business days",
            "vintage": "latest revised history; not point-in-time safe",
            "interpretation": "Positive values indicate above-average financial market stress.",
            "source": {
                "publisher": "Office of Financial Research",
                "page": OFR_FSI_PAGE,
                "download": OFR_FSI_URL,
            },
            "citation": (
                'Office of Financial Research, "OFR Financial Stress Index," '
                f"refreshed daily, {OFR_FSI_PAGE}"
            ),
            "disclaimer": (
                "Informational only; not investment advice. ArcOfMarket is not endorsed "
                "by the OFR or U.S. Treasury."
            ),
        },
        "series": series,
        "latest": {"date": date_values[-1], **latest_values},
    }


