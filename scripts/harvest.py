def _fetch_close(ticker: str) -> pd.Series | None:
    """拉指数收盘,容错:失败留痕到 _FAILURES 返回 None,不抛。"""
    result = CallResult.invoke(fetch_history, ticker)
    if result.succeeded:
        return result.unwrap()["Close"]
    error = result.error or RuntimeError("price history failed without an error")
    message = f"{type(error).__name__}: {str(error)[:120]}"
    _FAILURES.append({"section": f"fetch {ticker}", "error": message, "blocking": True})
    print(f"  ⚠️ {ticker} 拉取失败（跳过其面板并保留上一版）: {message}")
    return None


