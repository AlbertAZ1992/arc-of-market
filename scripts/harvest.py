# ------------------------------------------------------------ CFTC COT VIX 期货持仓
COT_TFF = "https://publicreporting.cftc.gov/resource/gpe5-46if.json"
COT_VALUE_FIELDS = (
    "date",
    "lev_long",
    "lev_short",
    "lev_net",
    "am_long",
    "am_short",
    "am_net",
    "oi",
    "lev_net_pct_oi",
    "am_net_pct_oi",
)
COT_SOURCE_FIELDS = {
    "lev_long": "lev_money_positions_long",
    "lev_short": "lev_money_positions_short",
    "am_long": "asset_mgr_positions_long",
    "am_short": "asset_mgr_positions_short",
    "oi": "open_interest_all",
}


def cot_row_hash(row: dict[str, Any]) -> str:
    """Hash the CFTC values that can be revised for one report date."""
    digest = hashlib.sha256()
    for field in COT_VALUE_FIELDS:
        digest.update(field.encode())
        digest.update(b"\x00")
        digest.update(repr(row.get(field)).encode())
        digest.update(b"\x1e")
    return digest.hexdigest()


def attach_cot_observations(
    series: list[dict[str, Any]],
    existing: dict[str, Any],
    observed_at: str,
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    """Preserve first-seen timestamps and record later CFTC revisions."""
    previous_rows = {
        row["date"]: row
        for row in existing.get("series", [])
        if isinstance(row, dict) and isinstance(row.get("date"), str)
    }
    revisions = [row for row in existing.get("revision_history", []) if isinstance(row, dict)]
    for row in series:
        digest = cot_row_hash(row)
        previous = previous_rows.get(row["date"], {})
        previous_hash = previous.get("row_sha256")
        first_observed_at = previous.get("first_observed_at", observed_at)
        if previous_hash and previous_hash != digest:
            revisions.append(
                {
                    "report_date": row["date"],
                    "detected_at": observed_at,
                    "previous_hash": previous_hash,
                    "new_hash": digest,
                }
            )
        row.update(
            {
                "first_observed_at": first_observed_at,
                "strict_available_at": first_observed_at,
                "row_sha256": digest,
            }
        )
    return series, revisions


def fetch_cftc_vix_positions() -> list[dict[str, Any]]:
    """Fetch and normalize CFTC Traders in Financial Futures VIX rows."""
    date_field = "report_date_as_yyyy_mm_dd"
    response = requests.get(
        COT_TFF,
        params={
            "$limit": "5000",
            "$order": f"{date_field} ASC",
            "$select": ",".join((date_field, *COT_SOURCE_FIELDS.values())),
            "$where": "starts_with(market_and_exchange_names,'VIX')",
        },
        headers=UA,
        timeout=60,
    )
    response.raise_for_status()
    rows = []
    for source_row in response.json():
        try:
            normalized: dict[str, Any] = {
                name: int(source_row[source_name])
                for name, source_name in COT_SOURCE_FIELDS.items()
            }
            report_date = str(source_row[date_field])[:10]
            open_interest = normalized["oi"]
            if open_interest <= 0:
                continue
            normalized["date"] = report_date
            normalized.update(cot_availability_dates(report_date))
            normalized["lev_net"] = normalized["lev_long"] - normalized["lev_short"]
            normalized["am_net"] = normalized["am_long"] - normalized["am_short"]
            normalized["lev_net_pct_oi"] = round(
                normalized["lev_net"] / open_interest * 100,
                2,
            )
            normalized["am_net_pct_oi"] = round(
                normalized["am_net"] / open_interest * 100,
                2,
            )
            rows.append(normalized)
        except (KeyError, TypeError, ValueError):
            continue
    if not rows:
        raise RuntimeError("CFTC TFF returned no valid VIX position rows")
    return sorted(rows, key=lambda row: str(row["date"]))


