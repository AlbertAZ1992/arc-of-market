def load_local_env(path: Path = ROOT / ".env") -> None:
    """加载简单的 KEY=value 本地配置，不覆盖调用方已设置的环境变量。"""
    if not path.exists():
        return
    parsed = parse_env_values(path.read_text(encoding="utf-8"))
    os.environ.update({key: value for key, value in parsed.items() if key not in os.environ})


def parse_env_values(text: str) -> dict[str, str]:
    values = {}
    for candidate in text.splitlines():
        line = candidate.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, raw_value = line.split("=", 1)
        normalized_key = key.strip()
        if normalized_key:
            values[normalized_key] = raw_value.strip().strip("\"'")
    return values


